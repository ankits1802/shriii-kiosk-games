/**
 * Generates the voice-line catalogue modules from `content/i18n/lines.yaml` (the canonical source).
 *
 *   node src/voice/catalogue/build-catalogue.ts           write the generated modules
 *   node src/voice/catalogue/build-catalogue.ts --check   fail if they are out of date (CI drift check)
 *
 * Two modules are produced:
 * - `lines.generated.ts`: ids, category, speaker role, never-voice flag, target duration and languages.
 *   Shipped in every build (needed for routing rules and preloading).
 * - `reference-text.generated.ts`: en-IN reference text for recording scripts. Imported ONLY by the dev
 *   Web Speech placeholder through a dynamic import that is compiled out of production builds.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

interface RawLine {
  id: string;
  category: string;
  module_id: string | null;
  speaker_role: string;
  reference_text: string;
  target_duration_ms: number;
  voice_forbidden: boolean;
  recording: Record<string, { status: string; itc_state: string }>;
}

interface RawCatalogue {
  catalogue_version: string;
  reference_language: string;
  languages: string[];
  lines: RawLine[];
}

const here = dirname(fileURLToPath(import.meta.url));
const yamlPath = resolve(here, '../../../../../content/i18n/lines.yaml');
const linesOut = resolve(here, 'lines.generated.ts');
const textOut = resolve(here, 'reference-text.generated.ts');

/** Render both modules from the YAML text. Exported for the drift test. */
export function renderCatalogue(yamlText: string): { lines: string; text: string } {
  const cat = parse(yamlText) as RawCatalogue;
  const header =
    '/* GENERATED by src/voice/catalogue/build-catalogue.ts from content/i18n/lines.yaml. Do not edit. */\n';
  const entries = cat.lines.map((l) => {
    const rec = Object.fromEntries(
      Object.entries(l.recording).map(([lang, r]) => [lang, r.status]),
    );
    return `  ${JSON.stringify(l.id)}: { category: ${JSON.stringify(l.category)}, moduleId: ${JSON.stringify(l.module_id)}, speakerRole: ${JSON.stringify(l.speaker_role)}, voiceForbidden: ${l.voice_forbidden}, targetDurationMs: ${l.target_duration_ms}, recording: ${JSON.stringify(rec)} },`;
  });
  const lines = `${header}import type { LineMeta } from './types.ts';

export const CATALOGUE_VERSION = ${JSON.stringify(cat.catalogue_version)};
export const REFERENCE_LANGUAGE = ${JSON.stringify(cat.reference_language)};
export const CATALOGUE_LANGUAGES: readonly string[] = ${JSON.stringify(cat.languages)};

export const LINES: Readonly<Record<string, LineMeta>> = {
${entries.join('\n')}
};
`;
  const textEntries = cat.lines.map(
    (l) => `  ${JSON.stringify(l.id)}: ${JSON.stringify(l.reference_text)},`,
  );
  const text = `${header}/** en-IN reference text: recording scripts and the DEV-ONLY placeholder voice. Never shipped in production builds. */
export const REFERENCE_TEXT: Readonly<Record<string, string>> = {
${textEntries.join('\n')}
};
`;
  return { lines, text };
}

/** Format generated TypeScript with the repo's Biome config so the output passes `pnpm lint`. */
function biomeFormat(source: string, filePath: string): string {
  const bin = resolve(here, '../../../../../node_modules/@biomejs/biome/bin/biome');
  return execFileSync(process.execPath, [bin, 'format', `--stdin-file-path=${filePath}`], {
    input: source,
    encoding: 'utf8',
    cwd: resolve(here, '../../../../..'),
    maxBuffer: 16 * 1024 * 1024,
  });
}

function main(): void {
  const raw = renderCatalogue(readFileSync(yamlPath, 'utf8'));
  const lines = biomeFormat(raw.lines, linesOut);
  const text = biomeFormat(raw.text, textOut);
  const check = process.argv.includes('--check');
  const read = (p: string): string => {
    try {
      return readFileSync(p, 'utf8');
    } catch {
      return '';
    }
  };
  if (check) {
    const drift = read(linesOut) !== lines || read(textOut) !== text;
    if (drift) {
      console.error(
        'voice catalogue is out of date: run `node src/voice/catalogue/build-catalogue.ts`',
      );
      process.exit(1);
    }
    console.log('voice catalogue up to date');
    return;
  }
  writeFileSync(linesOut, lines);
  writeFileSync(textOut, text);
  console.log('voice catalogue written');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
