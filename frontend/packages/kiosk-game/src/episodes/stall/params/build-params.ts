/**
 * Generates `params.generated.ts`: the scoring thresholds The Stall needs at schedule and run time,
 * read from the canonical YAML so they live in exactly one place (BUILD_DECISIONS non-negotiable 8):
 *
 * - `stats/scoring/src/shriii_scoring/data/scoring_params.yaml`
 *   - `tone.hostile_level_min`: customer tone level at or above which a rude-run customer is a
 *     provocation (places the provocations in the rude-customer run, paradigm `stallOverrides`);
 *   - `tone.min_distinct_levels_mirroring`: distinct customer tone levels the tone choices must span;
 *   - `tone.ordinal`: the closed tone codes (firm / neutral / warm) and their order;
 *   - `feedback_recovery.window_trials`: trials after scripted negative feedback that must follow
 *     inside the service block.
 * - `stats/measurement-model/dictionary/shared.yaml`, exclusion rule `anticipatory_response`: the
 *   premature cut-off used to classify committing taps (same value the scorer excludes on).
 *
 *   node src/episodes/stall/params/build-params.ts          write
 *   node src/episodes/stall/params/build-params.ts --check  fail on drift (CI)
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

/** Repository root: from this file when run by node, else from the package directory (vitest). */
function repoRoot(): string {
  if (import.meta.url.startsWith('file:')) {
    return resolve(dirname(fileURLToPath(import.meta.url)), '../../../../../../..');
  }
  return resolve(process.cwd(), '../../..');
}
const repo = repoRoot();
const here = resolve(repo, 'frontend/packages/kiosk-game/src/episodes/stall/params');
export const SCORING_PARAMS_PATH = resolve(
  repo,
  'stats/scoring/src/shriii_scoring/data/scoring_params.yaml',
);
export const SHARED_DICTIONARY_PATH = resolve(
  repo,
  'stats/measurement-model/dictionary/shared.yaml',
);
export const GENERATED_PATH = resolve(here, 'params.generated.ts');
const out = GENERATED_PATH;

interface ScoringParamsDoc {
  readonly version: string;
  readonly tone: {
    readonly ordinal: Readonly<Record<string, number>>;
    readonly hostile_level_min: number;
    readonly min_distinct_levels_mirroring: number;
  };
  readonly feedback_recovery: { readonly window_trials: number };
  readonly style: { readonly min_trials_per_segment: number; readonly risky_codes: string[] };
}

interface SharedDoc {
  readonly version: string;
  readonly exclusion_rules: readonly {
    readonly id: string;
    readonly when: readonly {
      readonly field: string;
      readonly op: string;
      readonly value: unknown;
    }[];
  }[];
}

function finiteInt(name: string, v: unknown): number {
  if (typeof v !== 'number' || !Number.isInteger(v) || v < 0) {
    throw new Error(`${name} must be a non-negative integer, got ${JSON.stringify(v)}`);
  }
  return v;
}

/** Render the generated module from the two YAML documents (exported for the drift test). */
export function renderStallParams(scoringYaml: string, sharedYaml: string): string {
  const p = parse(scoringYaml) as ScoringParamsDoc;
  const s = parse(sharedYaml) as SharedDoc;
  const rule = s.exclusion_rules.find((r) => r.id === 'anticipatory_response');
  const cond = rule?.when.find((c) => c.field === 'payload.latency_ms' && c.op === 'lt');
  if (!cond || typeof cond.value !== 'number') {
    throw new Error('shared.yaml: exclusion rule anticipatory_response (latency_ms lt) is missing');
  }
  const ordinal = Object.entries(p.tone.ordinal)
    .map(([code, rank]) => [code, finiteInt(`tone.ordinal.${code}`, rank)] as const)
    .sort((a, b) => a[1] - b[1]);
  if (ordinal.length < 2) throw new Error('tone.ordinal needs at least two codes');
  return `/* GENERATED by src/episodes/stall/params/build-params.ts from stats/scoring/src/shriii_scoring/data/scoring_params.yaml and stats/measurement-model/dictionary/shared.yaml. Do not edit. */

/** Version of the scoring parameter file these values were read from. */
export const SCORING_PARAMS_VERSION = ${JSON.stringify(p.version)};
/** Version of the shared dictionary the premature cut-off was read from. */
export const SHARED_DICTIONARY_VERSION = ${JSON.stringify(s.version)};

/** \`tone.hostile_level_min\`: a customer tone level at or above this is a provocation. */
export const HOSTILE_LEVEL_MIN = ${finiteInt('tone.hostile_level_min', p.tone.hostile_level_min)};
/** \`tone.min_distinct_levels_mirroring\`: distinct customer tone levels the tone choices must span. */
export const MIN_DISTINCT_TONE_LEVELS = ${finiteInt(
    'tone.min_distinct_levels_mirroring',
    p.tone.min_distinct_levels_mirroring,
  )};
/** \`feedback_recovery.window_trials\`: trials scored after each scripted negative feedback. */
export const FEEDBACK_WINDOW_TRIALS = ${finiteInt(
    'feedback_recovery.window_trials',
    p.feedback_recovery.window_trials,
  )};
/** \`tone.ordinal\` codes from the lowest to the highest ordinal (firm .. warm). */
export const TONE_CODES_BY_ORDINAL: readonly string[] = ${JSON.stringify(ordinal.map(([c]) => c))};
/** shared.yaml \`anticipatory_response\`: committing taps faster than this (ms) are premature. */
export const PREMATURE_THRESHOLD_MS = ${cond.value};
/** \`style.min_trials_per_segment\`: trials per comparable probe segment (\`probe_group_id\`). */
export const PROBE_SEGMENT_TRIALS = ${finiteInt(
    'style.min_trials_per_segment',
    p.style.min_trials_per_segment,
  )};
/** \`style.risky_codes\`: probe response codes the style model counts as the risky option. */
export const PROBE_RISKY_CODES: readonly string[] = ${JSON.stringify(p.style.risky_codes)};
`;
}

function biomeFormat(source: string, filePath: string): string {
  const bin = resolve(repo, 'node_modules/@biomejs/biome/bin/biome');
  return execFileSync(process.execPath, [bin, 'format', `--stdin-file-path=${filePath}`], {
    input: source,
    encoding: 'utf8',
    cwd: repo,
  });
}

/** The formatted generated text for the YAML currently on disk. */
export function currentGeneratedText(): string {
  return biomeFormat(
    renderStallParams(
      readFileSync(SCORING_PARAMS_PATH, 'utf8'),
      readFileSync(SHARED_DICTIONARY_PATH, 'utf8'),
    ),
    out,
  );
}

function main(): void {
  const text = currentGeneratedText();
  let current = '';
  try {
    current = readFileSync(out, 'utf8');
  } catch {
    current = '';
  }
  if (process.argv.includes('--check')) {
    if (current !== text) {
      console.error(
        'stall params are out of date: run `node src/episodes/stall/params/build-params.ts`',
      );
      process.exit(1);
    }
    console.log('stall params up to date');
    return;
  }
  writeFileSync(out, text);
  console.log('stall params written');
}

if (
  import.meta.url.startsWith('file:') &&
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
)
  main();
