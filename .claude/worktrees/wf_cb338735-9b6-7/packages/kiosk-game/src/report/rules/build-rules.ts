/**
 * Generates `rules.generated.ts` (the report display rule, limits, battery-gate minimum and per-construct
 * report caps) from the canonical YAML: `scoring/gates.yaml` and `scoring/dictionary/shared.yaml`.
 * Thresholds therefore live only in YAML (BUILD_DECISIONS non-negotiable 8).
 *
 *   node src/report/rules/build-rules.ts          write
 *   node src/report/rules/build-rules.ts --check  fail on drift (CI)
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../../../../..');
const gatesPath = resolve(repo, 'scoring/gates.yaml');
const sharedPath = resolve(repo, 'scoring/dictionary/shared.yaml');
const out = resolve(here, 'rules.generated.ts');

interface Gates {
  version: string;
  fail_closed: boolean;
  battery_gate: { min_language_groups: number; closed_behaviour: string };
  display_rule: {
    battery_gate: string;
    trait_status_in: string[];
    session_valid_for_report: boolean;
    exclude_not_enough_to_say: boolean;
    release_pack_valid_and_unexpired: boolean;
    report_mode: string;
  };
  report: {
    band_count: number;
    min_traits_shown: number;
    max_traits_shown: number;
    disclaimer_required: boolean;
  };
  release_pack: { default_expiry_days: number };
  trait_gate: {
    norms: {
      sem_rule: {
        ci_level: number;
        max_band_boundaries_overlapped: number;
        min_band_width_sem: number;
      };
    };
  };
  caps: { construct: string; max_status: string; stricter_flag: boolean }[];
  permanent_withhold: { construct: string; pathway: string }[];
}

interface Shared {
  version: string;
  constructs: {
    id: string;
    restricted: boolean;
    report: { max_status: string; phrase_keys: { pole_a: string; centre: string; pole_b: string } };
  }[];
}

/** Render the generated module text from the two YAML documents (exported for tests). */
export function renderRules(gatesYaml: string, sharedYaml: string): string {
  const g = parse(gatesYaml) as Gates;
  const s = parse(sharedYaml) as Shared;
  const rank = ['unvalidated', 'research_only', 'validated_broad_style', 'validated_banded'];
  const capOf = (id: string, own: string): string => {
    const cap = g.caps.find((c) => c.construct === id);
    if (!cap) return own;
    return rank.indexOf(cap.max_status) < rank.indexOf(own) ? cap.max_status : own;
  };
  const constructs = Object.fromEntries(
    s.constructs.map((c) => [
      c.id,
      {
        maxStatus: capOf(c.id, c.report.max_status),
        restricted: c.restricted || g.caps.some((x) => x.construct === c.id && x.stricter_flag),
        phraseKeys: c.report.phrase_keys,
      },
    ]),
  );
  return `/* GENERATED by src/report/rules/build-rules.ts from scoring/gates.yaml and scoring/dictionary/shared.yaml. Do not edit. */
import type { ConstructReportRule, DisplayRule, ReportLimits, SemRule } from './types.ts';

export const GATES_VERSION = ${JSON.stringify(g.version)};
export const SHARED_DICTIONARY_VERSION = ${JSON.stringify(s.version)};
export const FAIL_CLOSED = ${JSON.stringify(g.fail_closed)};

/** Show a trait iff ALL of these hold (gates.yaml display_rule). */
export const DISPLAY_RULE: DisplayRule = ${JSON.stringify({
    batteryGate: g.display_rule.battery_gate,
    traitStatusIn: g.display_rule.trait_status_in,
    sessionValidForReport: g.display_rule.session_valid_for_report,
    excludeNotEnoughToSay: g.display_rule.exclude_not_enough_to_say,
    releasePackValidAndUnexpired: g.display_rule.release_pack_valid_and_unexpired,
    reportMode: g.display_rule.report_mode,
  })};

export const REPORT_LIMITS: ReportLimits = ${JSON.stringify({
    bandCount: g.report.band_count,
    minTraitsShown: g.report.min_traits_shown,
    maxTraitsShown: g.report.max_traits_shown,
    disclaimerRequired: g.report.disclaimer_required,
    batteryMinLanguageGroups: g.battery_gate.min_language_groups,
    releasePackDefaultExpiryDays: g.release_pack.default_expiry_days,
  })};

/** "Not enough to say" rule (gates.yaml trait_gate.sem_rule). */
export const SEM_RULE: SemRule = ${JSON.stringify({
    ciLevel: g.trait_gate.norms.sem_rule.ci_level,
    maxBandBoundariesOverlapped: g.trait_gate.norms.sem_rule.max_band_boundaries_overlapped,
    minBandWidthSem: g.trait_gate.norms.sem_rule.min_band_width_sem,
  })};

/** Per-construct report caps and phrase keys (shared.yaml report.max_status, tightened by gates.yaml caps). */
export const CONSTRUCT_REPORT: Readonly<Record<string, ConstructReportRule>> = ${JSON.stringify(constructs)};

/** (construct, pathway) pairs that are never reported (gates.yaml permanent_withhold). */
export const PERMANENT_WITHHOLD: readonly { readonly construct: string; readonly pathway: string }[] = ${JSON.stringify(g.permanent_withhold.map((w) => ({ construct: w.construct, pathway: w.pathway })))};
`;
}

function biomeFormat(source: string, filePath: string): string {
  const bin = resolve(repo, 'node_modules/@biomejs/biome/bin/biome');
  return execFileSync(process.execPath, [bin, 'format', `--stdin-file-path=${filePath}`], {
    input: source,
    encoding: 'utf8',
    cwd: repo,
  });
}

function main(): void {
  const text = biomeFormat(
    renderRules(readFileSync(gatesPath, 'utf8'), readFileSync(sharedPath, 'utf8')),
    out,
  );
  let current = '';
  try {
    current = readFileSync(out, 'utf8');
  } catch {
    current = '';
  }
  if (process.argv.includes('--check')) {
    if (current !== text) {
      console.error('report rules are out of date: run `node src/report/rules/build-rules.ts`');
      process.exit(1);
    }
    console.log('report rules up to date');
    return;
  }
  writeFileSync(out, text);
  console.log('report rules written');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
